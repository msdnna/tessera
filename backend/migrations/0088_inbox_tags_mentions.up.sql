-- «Входящие» (#3040): теги и @-упоминания у записи (заметки и напоминания).
--
--   * tags — имена, как их написал автор после «#» (без решётки). Запись,
--     привязанная к задаче или проекту, носит теги этого проекта: сервер
--     приводит имя к написанию тега проекта (сравнение trim + lower, как у всех
--     читателей тегов), а клиент красит пилл цветом тега. Совпадения нет или
--     проекта нет — это свободная метка записи. Имена, а не M:N на tags: личная
--     запись не должна участвовать в жизненном цикле тегов проекта (слияние,
--     массовое удаление с undo, перенос проекта), а метку, которую автор
--     написал, запись не теряет, даже если тег проекта удалят.
--   * mentions — кого упомянули (id участников пространства). Для общей заметки
--     новые упомянутые получают уведомление `mention`; личная заметка и
--     напоминание (оно всегда личное) никого не уведомляют — упоминание
--     остаётся ссылкой на человека.
--
-- Аддитивная и повторяемая.

