package handlers

import (
	"testing"
	"time"

	"tessera/internal/db"
)

// lead и repeat уведомления о сроке — int32, и перед записью стоял только
// кламп снизу (`< 0 → 0`) в обеих ручках: PUT /notification-prefs и
// POST /tasks/:id/due-notify. Значение, которого ни один клиент не предлагает,
// уходило прямо в `time.Duration(x) * time.Minute`, а с 153722868 умножение
// переполняет int64 и длительность выходит ОТРИЦАТЕЛЬНОЙ.
//
// Оба поля от этого ломаются в противоположные стороны, и оба раза — в сторону,
// обратную тому, что просили:
//   - repeat: следующий повтор считается как last_fired_at + интервал. С
//     отрицательным интервалом он всегда в прошлом, и «повторять раз в 4084
//     года» (int32-максимум) становится «долби каждую минуту» — сканер тикает
//     раз в минуту и фирит на каждом тике, пока задача просрочена.
//   - lead: окно считается как due − lead. С отрицательным lead окно уезжает
//     ЗА срок, и «предупреди за 4084 года» становится «молчи до трёх суток
//     после дедлайна».
//
// Тот же класс, что уже закрытые digest_minutes и quiet_tz (#2932): значение,
// принятое молча, позже даёт не то поведение, о котором говорит экран.
func TestDueLeadAndRepeatAreBounded(t *testing.T) {
	due := time.Date(2026, 9, 20, 12, 0, 0, 0, time.UTC)
	now := due.Add(2 * time.Hour) // задача просрочена на два часа

	// Находка (repeat): интервал, которого никто не мог иметь в виду, обязан
	// означать «реже, чем сейчас», а не «на каждом тике». 153722868 — первое
	// переполняющее, 2147483647 — int32-максимум.
	for _, repeat := range []int32{153722868, 1000000000, 2147483647} {
		var prior db.DueNotificationState
		prior.FiredDue = due
		prior.LastFiredAt = now.Add(-time.Minute) // повторили минуту назад
		if dueShouldFire(now, due, 60, repeat, &prior) {
			t.Errorf("repeat=%d: повтор сработал через минуту после прошлого — "+
				"интервал переполнился и стал отрицательным, это долбёжка каждую минуту", repeat)
		}
	}

	// Находка (lead): «предупреди сильно заранее» не может означать «молчи
	// после срока». Задача уже просрочена — первое предупреждение обязано уйти.
	for _, lead := range []int32{153722868, 1000000000, 2147483647} {
		if !dueShouldFire(now, due, lead, 0, nil) {
			t.Errorf("lead=%d: задача просрочена на два часа, а предупреждение молчит — "+
				"окно переполнилось и уехало за срок", lead)
		}
	}

	// Контроль: обычные значения считаются в точности как раньше.
	// Одноразовое предупреждение внутри окна — фирит.
	if !dueShouldFire(due.Add(-30*time.Minute), due, 60, 0, nil) {
		t.Error("контроль: за полчаса до срока при лиде 60 минут предупреждение обязано сработать")
	}
	// До окна — молчит.
	if dueShouldFire(due.Add(-2*time.Hour), due, 60, 0, nil) {
		t.Error("контроль: за два часа до срока при лиде 60 минут предупреждать рано")
	}
	// Повтор раз в 15 минут: через 10 минут рано, через 20 — пора.
	var prior db.DueNotificationState
	prior.FiredDue = due
	prior.LastFiredAt = now.Add(-10 * time.Minute)
	if dueShouldFire(now, due, 60, 15, &prior) {
		t.Error("контроль: повтор раз в 15 минут не должен срабатывать через 10")
	}
	prior.LastFiredAt = now.Add(-20 * time.Minute)
	if !dueShouldFire(now, due, 60, 15, &prior) {
		t.Error("контроль: повтор раз в 15 минут обязан сработать через 20")
	}
	// Повтор выключен (0) — второй раз не фирит.
	prior.LastFiredAt = now.Add(-24 * time.Hour)
	if dueShouldFire(now, due, 60, 0, &prior) {
		t.Error("контроль: без повтора второе уведомление не отправляется")
	}
}
