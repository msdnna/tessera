package website.msdnna.tessera.util

// Правила, по которым работает пикер аватара (#2932).
//
// Это правила сервера, пересказанные здесь: `handlers/users.go` (UploadMyAvatar)
// отказывает всему тяжелее 2 МиБ и всему, что не опознаётся как PNG/JPEG/GIF/WebP.
// У пикера своих правил не было вовсе, так что оба отказа приезжали с сервера
// английской фразой («avatar exceeds 2 MiB») — и в единицах, отличных от подсказки
// строкой выше («до 2 МБ»). Сказать это здесь — значит сказать до загрузки, а не
// после неё, на языке читателя: снимок с камеры почти всегда тяжелее 2 МиБ, а
// HEIF-кадр с современного телефона сервер не примет ни при каком размере.
//
// Зеркало `frontend/src/utils/avatar.js` — держать в синхроне.

/** Серверный `maxAvatarBytes`. */
const val AVATAR_MAX_BYTES: Long = 2L * 1024 * 1024

/** Типы, которые пропускает серверный сниффер, в его же порядке. */
val AVATAR_TYPES = listOf("image/png", "image/jpeg", "image/gif", "image/webp")

/** Почему сервер отказал бы этому файлу — решено до того, как он отправлен. */
enum class AvatarPickError { TooLarge, BadType }

/**
 * Проверка выбранного файла по правилам сервера.
 *
 * Размер сверяется точно — сервер считает те же байты. Проверка типа намеренно
 * односторонняя: она срабатывает лишь на типе, который система РЕАЛЬНО назвала и
 * который сервер точно отвергнет. Файл без типа (`getType` вернул null на
 * документ-провайдере, который его не знает) едет как есть: сервер смотрит на
 * БАЙТЫ, и отказ здесь сделал бы пикер строже сервера — он завернул бы картинку,
 * которую тот бы принял.
 */
fun avatarPickError(size: Long, mime: String?): AvatarPickError? {
    if (size > AVATAR_MAX_BYTES) return AvatarPickError.TooLarge
    // Тип с параметрами («image/jpeg; charset=utf-8» от иного провайдера) —
    // это тот же тип: сравнивается то, что до точки с запятой.
    val type = mime?.substringBefore(';')?.trim()?.lowercase().orEmpty()
    if (type.isNotEmpty() && type !in AVATAR_TYPES) return AvatarPickError.BadType
    return null
}
